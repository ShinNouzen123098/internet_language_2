-- ============================================
-- Создание таблиц
-- ============================================

-- Таблица команд
CREATE TABLE IF NOT EXISTS teams (
    id      SERIAL PRIMARY KEY,         -- автоинкремент, первичный ключ
    name    VARCHAR(100) NOT NULL,      -- название команды
    city    VARCHAR(100) NOT NULL       -- город
);

-- Таблица игроков (связана с командами: один-ко-многим)
CREATE TABLE IF NOT EXISTS players (
    id          SERIAL PRIMARY KEY,
    name        VARCHAR(150) NOT NULL,      -- полное имя
    position    VARCHAR(100) NOT NULL,      -- амплуа
    birth_date  DATE NOT NULL,              -- дата рождения
    height      INT  NOT NULL,              -- рост в см
    team_id     INT  REFERENCES teams(id)   -- внешний ключ → teams.id
                     ON DELETE SET NULL     -- если команду удалят, игрок останется без команды
);

-- Таблица новостей
CREATE TABLE IF NOT EXISTS news (
    id          SERIAL PRIMARY KEY,
    title       VARCHAR(255) NOT NULL,      -- заголовок
    content     TEXT NOT NULL,              -- текст новости
    image_path  VARCHAR(255),               -- путь к картинке
    created_at  TIMESTAMP DEFAULT NOW()     -- дата создания, ставится автоматически
);

